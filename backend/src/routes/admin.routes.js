const express=require('express');
const router=express.Router();
const c=require('../controllers/admin.controller');
const {authenticate,requireAdmin}=require('../middleware/auth.middleware');
router.use(authenticate,requireAdmin);
router.get('/overview',c.overview);
router.get('/stats',c.overview);
router.get('/students/:id/analysis',c.studentAnalysis);
router.get('/students',c.students);
router.patch('/students/:id/status',c.setStudentStatus);
router.delete('/students/:id',c.deleteStudent);
router.get('/teachers',c.teachers);
router.post('/teachers',c.createTeacher);
router.patch('/teachers/:id',c.updateTeacher);
router.delete('/teachers/:id',c.deleteTeacher);
router.patch('/students/:studentId/teacher',c.assignTeacher);
router.get('/complaints',c.complaints);
router.patch('/complaints/:id',c.updateComplaint);
router.get('/activity',c.activity);
router.get('/resources',c.resources);
router.post('/resources',c.createResource);
router.delete('/resources/:id',c.deleteResource);
module.exports=router;
